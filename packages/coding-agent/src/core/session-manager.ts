function buildEntryIndex(entries: SessionEntry[], byId?: Map<string, SessionEntry>): Map<string, SessionEntry> {
	if (byId) return byId;
	const index = new Map<string, SessionEntry>();
	for (const entry of entries) {
		if (typeof entry.id !== "string" || !entry.id.trim()) throw new Error("Session entry id must be non-empty");
		if (index.has(entry.id)) throw new Error(`Duplicate session entry id: ${entry.id}`);
		index.set(entry.id, entry);
	}
	return index;
}

/** Validate detached loaded entries before replacing a manager or publishing a fork. Orphans remain supported. */
function validateSessionGraph(entries: FileEntry[]): void {
	const index = buildEntryIndex(entries.filter((entry): entry is SessionEntry => entry.type !== "session"));
	const checked = new Set<string>();
	for (const entry of index.values()) {
		const visiting = new Set<string>();
		let current: SessionEntry | undefined = entry;
		while (current && !checked.has(current.id)) {
			if (visiting.has(current.id)) throw new Error(`Cycle in session parent links: ${current.id}`);
			visiting.add(current.id);
			current = current.parentId ? index.get(current.parentId) : undefined;
		}
		for (const id of visiting) checked.add(id);
	}
}

function buildSessionPath(
	entries: SessionEntry[],
	leafId?: string | null,
	byId?: Map<string, SessionEntry>,
): SessionEntry[] {
	const index = buildEntryIndex(entries, byId);
	let leaf: SessionEntry | undefined;
	if (leafId === null) {
		return [];
	}
	if (leafId) {
		leaf = index.get(leafId);
	}
	leaf ??= entries[entries.length - 1];
	if (!leaf) {
		return [];
	}

	const path: SessionEntry[] = [];
	const visited = new Set<string>();
	let current: SessionEntry | undefined = leaf;
	while (current) {
		if (visited.has(current.id)) throw new Error(`Cycle in session parent links: ${current.id}`);
		visited.add(current.id);
		path.push(current);
		current = current.parentId ? index.get(current.parentId) : undefined;
	}
	path.reverse();
	return path;
}

function getSessionContextSettings(path: SessionEntry[]): Pick<SessionContext, "thinkingLevel" | "model"> {
	let thinkingLevel = "off";
	let model: { provider: string; modelId: string } | null = null;

	for (const entry of path) {
		if (entry.type === "thinking_level_change") {
			thinkingLevel = entry.thinkingLevel;
		} else if (entry.type === "model_change") {
			model = { provider: entry.provider, modelId: entry.modelId };
		} else if (entry.type === "message" && entry.message.role === "assistant") {
			model = { provider: entry.message.provider, modelId: entry.message.model };
		}
	}

	return { thinkingLevel, model };
}

/**
 * Project one selected session entry into LLM/runtime messages.
 * Plain custom entries are display/state entries and do not participate in context.
 */
export function sessionEntryToContextMessages(entry: SessionEntry): AgentMessage[] {
	if (entry.type === "message") {
		const message = entry.message;
		// Session files are parsed without validation; old versions, forks, or
		// hand-edited files can contain messages with null/missing content.
		if (
			(message.role === "user" || message.role === "assistant" || message.role === "toolResult") &&
			message.content == null
		) {
			return [{ ...message, content: [] }];
		}
		return [message];
	}
	if (entry.type === "custom_message") {
		return [
			createCustomMessage(entry.customType, entry.content ?? [], entry.display, entry.details, entry.timestamp),
		];
	}
	if (entry.type === "branch_summary" && entry.summary) {
		return [createBranchSummaryMessage(entry.summary, entry.fromId, entry.timestamp)];
	}
	if (entry.type === "compaction" && entry.summary) {
		return [createCompactionSummaryMessage(entry.summary, entry.tokensBefore, entry.timestamp)];
	}
	return [];
}

/**
 * Build the active, compaction-aware session entry list.
 *
 * This follows the current leaf path. If the path contains compaction entries,
 * the latest compaction is represented by the compaction entry itself, followed
 * by the kept entries starting at firstKeptEntryId and all entries after the
 * compaction entry. Older summarized entries are omitted.
 */
export function buildContextEntries(
	entries: SessionEntry[],
	leafId?: string | null,
	byId?: Map<string, SessionEntry>,
): SessionEntry[] {
	const path = buildSessionPath(entries, leafId, byId);
	let compaction: CompactionEntry | null = null;

	for (const entry of path) {
		if (entry.type === "compaction") {
			compaction = entry;
		}
	}

	if (!compaction) {
		return path;
	}

	const compactionIdx = path.findIndex((entry) => entry.id === compaction.id);
	if (compactionIdx < 0) {
		return path;
	}

	const contextEntries: SessionEntry[] = [compaction];
	let foundFirstKept = false;
	for (let i = 0; i < compactionIdx; i++) {
		const entry = path[i];
		if (compaction.firstKeptEntryId && entry.id === compaction.firstKeptEntryId) {
			foundFirstKept = true;
		}
		if (foundFirstKept) {
			contextEntries.push(entry);
		}
	}
	contextEntries.push(...path.slice(compactionIdx + 1));
	return contextEntries;
}

/**
 * Build the branch entries shown in the interactive transcript.
 *
 * Modern replacement-history checkpoints only change provider context. They
 * remain transparent to the transcript so compaction cannot erase visible
 * session history. Legacy summary checkpoints retain their historical display
 * behavior and replace the older transcript prefix with their summary + tail.
 */
export function buildTranscriptEntries(
	entries: SessionEntry[],
	leafId?: string | null,
	byId?: Map<string, SessionEntry>,
): SessionEntry[] {
	const path = buildSessionPath(entries, leafId, byId).filter(
		(entry) =>
			entry.type !== "custom" ||
			(entry.customType !== "pi-task-recovery" && entry.customType !== "pi-tool-interruption"),
	);
	let legacyCompaction: CompactionEntry | undefined;

	for (const entry of path) {
		if (entry.type === "compaction" && !Array.isArray(entry.replacementHistory)) {
			legacyCompaction = entry;
		}
	}

	if (!legacyCompaction) return path;

	const compactionIdx = path.findIndex((entry) => entry.id === legacyCompaction.id);
	if (compactionIdx < 0) return path;

	const transcriptEntries: SessionEntry[] = [legacyCompaction];
	let foundFirstKept = false;
	for (let index = 0; index < compactionIdx; index++) {
		const entry = path[index];
		if (legacyCompaction.firstKeptEntryId && entry.id === legacyCompaction.firstKeptEntryId) {
			foundFirstKept = true;
		}
		if (foundFirstKept) transcriptEntries.push(entry);
	}
	transcriptEntries.push(...path.slice(compactionIdx + 1));
	return transcriptEntries;
}

/**
 * Build the session context from entries using tree traversal.
 * If leafId is provided, walks from that entry to root.
 * Handles compaction and branch summaries along the path.
 */
export function buildSessionContext(
	entries: SessionEntry[],
	leafId?: string | null,
	byId?: Map<string, SessionEntry>,
): SessionContext {
	const path = buildSessionPath(entries, leafId, byId);
	const { thinkingLevel, model } = getSessionContextSettings(path);
	let checkpointIndex = -1;
	let replacementHistory: AgentMessage[] | undefined;
	for (let index = path.length - 1; index >= 0; index--) {
		const entry = path[index];
		if (entry.type === "compaction" && Array.isArray(entry.replacementHistory)) {
			checkpointIndex = index;
			replacementHistory = entry.replacementHistory;
			break;
		}
	}
	if (replacementHistory) {
		return {
			messages: [...replacementHistory, ...path.slice(checkpointIndex + 1).flatMap(sessionEntryToContextMessages)],
			thinkingLevel,
			model,
		};
	}
	const messages = buildContextEntries(entries, leafId, byId).flatMap(sessionEntryToContextMessages);
	return { messages, thinkingLevel, model };
}

/**
 * Compute the default session directory for a cwd.
 * Encodes cwd into a safe directory name under ~/.pi/agent/sessions/.
 */
function getDefaultSessionDirPath(cwd: string, agentDir: string = getDefaultAgentDir()): string {
	const resolvedCwd = resolvePath(cwd);
	const resolvedAgentDir = resolvePath(agentDir);
	const safePath = `--${resolvedCwd.replace(/^[/\\]/, "").replace(/[/\\:]/g, "-")}--`;
	return join(resolvedAgentDir, "sessions", safePath);
}

export function getDefaultSessionDir(cwd: string, agentDir: string = getDefaultAgentDir()): string {
	const sessionDir = getDefaultSessionDirPath(cwd, agentDir);
	if (!existsSync(sessionDir)) {
		mkdirSync(sessionDir, { recursive: true });
	}
	return sessionDir;
}

